export const replayChecksSchema=`CREATE TABLE IF NOT EXISTS replay_checks (
 id TEXT PRIMARY KEY,match_id TEXT NOT NULL,created INTEGER NOT NULL,fingerprint TEXT NOT NULL UNIQUE,data TEXT NOT NULL);
 CREATE INDEX IF NOT EXISTS replay_checks_match ON replay_checks(match_id,created);`;
export const replayFingerprint=value=>createHash('sha256').update(JSON.stringify(value)).digest('hex');
const canonical=n=>n==='Verwüster'?'Zerstörer':n==='Bientank'?'Bienenkorb':n;
const actions=new Set(['add','upgrade','multiply','multiply_upgrade','spell']);

// Independent expected numbers are deliberately written out, not generated by
// the calculator being checked. These prove arithmetic, not in-game causality.
export function mechanicsRegression(calculate=calculateFormEffect){
 const forms=[{id:'base',unit:'Merlinor'},{id:'grown',unit:'Merlinor'}];
 const inventory={actor:'player',side:'own',matchId:'fixture',captureId:1,units:[{name:'Merlinor',totalCount:12,forms:[{formId:'base',count:2},{formId:'grown',count:10}]}]};
 const binding={actor:'player',confirmed:true,scopeConfirmed:true,sourceFormId:'base',targetFormId:'grown'};
 const run=(action,extra={})=>calculate({offer:{name:'Merlinor',action,quantity:action.includes('multiply')?2:1},inventory,binding,forms,mechanisms:defaultMechanisms,matchId:'fixture',captureId:1,...extra});
 const check=(id,fn)=>{try{return {id,status:fn()?'passed':'contradicted'};}catch{return {id,status:'contradicted'};}};
 return [check('2+10_double_source',()=>{const v=run('multiply');return v.known&&v.affectedCount===2&&v.afterTotal===14&&v.after.units[0].forms.find(f=>f.formId==='grown').count===10;}),
  check('2+10_upgrade_source',()=>{const v=run('upgrade');return v.known&&v.affectedCount===2&&v.afterTotal===12&&v.after.units[0].forms.find(f=>f.formId==='grown').count===12;}),
  check('combined_unconfirmed',()=>run('multiply_upgrade').known===false),
  check('unknown_source_not_total',()=>{const unknown=structuredClone(inventory);unknown.units[0].forms[0].count=null;return run('multiply',{inventory:unknown}).known===false;}),
  check('conflict_blocks_calculation',()=>run('upgrade',{mechanisms:[...defaultMechanisms,{unit:'*',action:'upgrade',status:'conflict'}]}).known===false)];
}

export function compareConfirmedImage(frame,reference){
 const comparisons=[];
 for(const side of ['own','enemy']){
  const truth=reference.fieldConfirmations?.[side];if(truth?.actor!=='player')continue;
  const predicted=frame.armyObservation?.sides?.[side]?.groups??[],names=predicted.map(g=>canonical(g.name));
  const groups=truth.groups.filter(g=>g.typeConfirmed),missing=groups.filter(g=>!names.includes(canonical(g.name))).map(g=>canonical(g.name));
  const extra=truth.typesComplete?names.filter(n=>!groups.some(g=>canonical(g.name)===n)):[];
  const counts=groups.filter(g=>g.count!=null).map(g=>{const p=predicted.find(p=>canonical(p.name)===canonical(g.name));const exact=p?.visibleMaximum===p?.visibleMinimum&&Number.isInteger(p?.visibleMinimum)?p.visibleMinimum:null;return {name:g.name,expected:g.count,actual:exact,status:exact==null?'unclear':exact===g.count?'passed':'contradicted'};});
  comparisons.push({side,referenceId:reference.id,revision:truth.revision,assisted:reference.reviewAssisted===true,missing,extra,counts,
   status:missing.length||extra.length||counts.some(c=>c.status==='contradicted')?'contradicted':!truth.typesComplete||counts.some(c=>c.status==='unclear')?'unclear':'passed'});
 }
 return comparisons;
}

export async function replayAudit({game,rules,collectionFor,matchups,referenceData=[],contextFor=async()=>({}),engine,guard=()=>{},calculate=calculateFormEffect}){
 const at=Date.now(),mechanics=mechanicsRegression(calculate),blocked=mechanics.some(r=>r.status!=='passed');
 const active=rules.filter(r=>r.status==='aktiv');
 const candidates=rules.filter(r=>['aktiv','test'].includes(r.status)&&r.offer&&Number.isFinite(r.weight));
 const reports=candidates.map(rule=>({id:rule.id,revision:replayFingerprint(rule),texts:rule.texts??{},status:'unclear',eligible:0,changed:0,unchanged:0,unverified:0,examples:[]}));
 const recognition=[],basis=[],coverage={de:0,en:0},frames=(game.reviewFrames??[]).filter(f=>['battle_choice','deck_choice','spell_choice'].includes(f.phase));
 for(const original of frames){
  await yieldToGame();guard();
  const refs=referenceData.filter(r=>r.matchId===game.id&&r.captureId===original.id).sort((a,b)=>(b.at??0)-(a.at??0));
  const own=refs.find(r=>r.fieldConfirmations?.own?.actor==='player')?.fieldConfirmations.own;
  const enemy=refs.find(r=>r.fieldConfirmations?.enemy?.actor==='player')?.fieldConfirmations.enemy;
  for(const ref of refs)recognition.push(...compareConfirmedImage(original,ref).map(row=>({...row,capture:original.id})));
  const context=await contextFor(game.id,original.id),frame={...original,...context,matchId:game.id,sourceCaptureId:original.id};
  const collection=await collectionFor(original.versions?.collection??game.versions?.collection);
  const missing=[];
  if(!collection)missing.push('historical_collection');
  if(!own?.typesComplete)missing.push('confirmed_own_types');
  if(!enemy?.typesComplete)missing.push('confirmed_enemy_types');
  if(!frame.offers?.length||frame.offers.some(o=>!o.name||!actions.has(o.action)))missing.push('complete_offers');
  if(frame.offers?.some(o=>['upgrade','multiply','multiply_upgrade'].includes(o.action)&&!calculate({offer:o,inventory:context.formInventory,binding:context.formBindings?.[o.position],forms:context.formCatalog,mechanisms:context.mechanisms,matchId:game.id,captureId:frame.id}).known))missing.push('confirmed_affected_form');
  basis.push({capture:frame.id,missing,status:missing.length?'unclear':'available'});coverage[frame.language==='en'?'en':'de']++;
  if(!collection||blocked)continue;
  const tip=list=>{const a=recommend(frame,game.mode,collection,matchups,false,list);const t=a.best??a.fallback??a.provisional;return t?{index:t.index,name:t.name,action:frame.offers[t.index]?.action,score:t.score}:null;};
  for(const [i,rule] of candidates.entries()){
   if(rule.mode&&rule.mode!=='beide'&&rule.mode!==game.mode||rule.phase&&rule.phase!=='alle'&&rule.phase!==frame.phase||!frame.offers.some(o=>canonical(o.name)===canonical(rule.offer)&&(!rule.action||rule.action==='alle'||rule.action===o.action))||rule.enemy&&!(frame.enemy??[]).some(e=>canonical(e.name)===canonical(rule.enemy)))continue;
   const report=reports[i],baseline=active.filter(r=>r.id!==rule.id),before=tip(baseline),after=tip([...baseline,{...rule,status:'aktiv'}]);
   if(!before||!after)continue;
   report.eligible++;report.unverified+=missing.length?1:0;
   const changed=before.index!==after.index;report[changed?'changed':'unchanged']++;
   if(report.examples.length<4||changed&&report.examples.every(e=>!e.changed))report.examples.push({capture:frame.id,before,after,changed,basis:missing.length?'unclear':'available',missing});
  }
 }
 guard();
 for(const r of reports)r.status=blocked?'blocked_by_mechanics':r.eligible?'replayed':'unclear';
 return {schema:1,kind:'replay_checks',matchId:game.id,outcome:game.outcome??'unbekannt',mode:game.mode,language:game.language,engine,created:at,elapsedMs:Date.now()-at,
  mechanics,blocked,recognition,basis,rules:reports,coverage,
  counts:{decisions:frames.length,changes:reports.reduce((n,r)=>n+r.changed,0),unclear:basis.filter(b=>b.missing.length).length,recognitionContradictions:recognition.filter(r=>r.status==='contradicted').length},
  tacticalEffect:'not_established',automaticActivation:false,expectations:'structured_rule_comparisons_only; free-text interpretation pending independent confirmation'};
}

export function createReplayChecksStore(withDatabase){
 const decode=r=>r?{...r,data:JSON.parse(r.data)}:null;
 return {
  candidates:async extra=>withDatabase(true,db=>{const rows=db.prepare("SELECT id,status,updated,data FROM match_runs WHERE status='completed' ORDER BY updated DESC LIMIT 20").all();for(const id of extra??[])if(!rows.some(r=>r.id===id)){const row=db.prepare("SELECT id,status,updated,data FROM match_runs WHERE id=? AND status='completed'").get(id);if(row)rows.push(row);}return rows.map(r=>({...r,match:restoreMatch(r.data),data:undefined}));}),
  version:async hash=>withDatabase(true,db=>{const r=db.prepare("SELECT data FROM runtime_versions WHERE hash=? AND kind='collection'").get(hash??'');return r?JSON.parse(r.data):null;}),
  has:async fingerprint=>withDatabase(true,db=>!!db.prepare('SELECT 1 FROM replay_checks WHERE fingerprint=?').get(fingerprint)),
  save:async(fingerprint,data)=>withDatabase(false,db=>db.prepare('INSERT OR IGNORE INTO replay_checks VALUES(?,?,?,?,?)').run(fingerprint.slice(0,24),data.matchId,Date.now(),fingerprint,JSON.stringify(data))),
  list:async()=>withDatabase(true,db=>db.prepare('SELECT * FROM replay_checks r WHERE rowid=(SELECT max(rowid) FROM replay_checks s WHERE s.match_id=r.match_id) ORDER BY created DESC LIMIT 30').all().map(decode))
 };
}
